// Extracts SF Symbols path data from @bradleyhodges/sfsymbols into a TS module.
const { execSync } = require("child_process");
const fs = require("fs");
const path = require("path");

const pkg = require("@bradleyhodges/sfsymbols");

// SF names used across the TwoLink app.
const NAMES = [
  "message",
  "message.fill",
  "gear",
  "photo.stack",
  "magnifyingglass",
  "heart.fill",
  "heart",
  "xmark.circle.fill",
  "xmark",
  "chevron.right",
  "chevron.left",
  "chevron.down",
  "chevron.up",
  "bell.slash.fill",
  "arrow.counterclockwise",
  "arrow.up",
  "plus",
  "bubble.left.and.bubble.right",
  "video",
  "photo",
  "mic.fill",
  "paperplane",
  "circle",
  "arrowshape.turn.up.left",
  "arrowshape.turn.up.right",
  "checkmark",
  "person.2",
  "trash",
];

const bySource = {};
for (const [key, entry] of Object.entries(pkg)) {
  if (entry && entry.sourceName) bySource[entry.sourceName] = entry;
}

// expo-symbols aliases -> real SF source names.
const ALIASES = { "mic.fill": "microphone.fill" };

const out = {};
const missing = [];
for (const name of NAMES) {
  const e = bySource[ALIASES[name] ?? name];
  if (!e) {
    missing.push(name);
    continue;
  }
  out[name] = {
    viewBox: e.viewBox,
    paths: e.svgPathData.map((p) => ({
      d: p.d,
      ...(p.fillOpacity != null ? { fillOpacity: p.fillOpacity } : {}),
    })),
  };
}

if (missing.length) {
  console.error("MISSING:", missing.join(", "));
  process.exit(1);
}

const ts =
  `// Generated by scripts/extract-sf-icons.js — Apple SF Symbols artwork.\n` +
  `// NOTE: Apple's license restricts SF Symbols to Apple platforms. See README.\n` +
  `export type SFSymbolName = ${NAMES.map((n) => `"${n}"`).join(" | ")};\n\n` +
  `export const SF_ICONS: Record<SFSymbolName, { viewBox: string; paths: { d: string; fillOpacity?: number }[] }> = ` +
  JSON.stringify(out, null, 2) +
  `;\n`;

const dest = path.join(__dirname, "..", "src", "ui", "sf-icons.ts");
fs.writeFileSync(dest, ts);
console.log("wrote", dest, `(${NAMES.length} icons)`);
